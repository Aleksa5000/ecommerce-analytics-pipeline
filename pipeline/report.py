"""Self-contained static HTML report (plotly.js inlined, no network needed)."""

import html
from pathlib import Path

import duckdb
from plotly.offline import get_plotlyjs

from . import analytics as an
from . import charts

CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,sans-serif;margin:0;background:#f8fafc;color:#0f172a}
main{max-width:1100px;margin:0 auto;padding:24px 16px 48px}
h1{margin:0 0 4px}h2{margin:36px 0 4px}p.sub{color:#475569;margin:0 0 12px}
.cards{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px;margin:20px 0}
.card{background:#fff;border:1px solid #e2e8f0;border-radius:10px;padding:14px}
.card b{display:block;font-size:1.5rem}.card span{color:#64748b;font-size:.85rem}
section{background:#fff;border:1px solid #e2e8f0;border-radius:10px;padding:12px 16px;margin-top:12px}
table{border-collapse:collapse;width:100%;font-size:.9rem}
th,td{padding:6px 8px;border-bottom:1px solid #e2e8f0;text-align:right}
th:first-child,td:first-child,th:nth-child(2),td:nth-child(2){text-align:left}
footer{color:#64748b;font-size:.85rem;margin-top:32px}
"""


def _fig(fig) -> str:
    return fig.to_html(full_html=False, include_plotlyjs=False, config={"displaylogo": False})


def _section(title: str, sub: str, body: str) -> str:
    return f"<h2>{title}</h2><p class='sub'>{sub}</p><section>{body}</section>"


def _products_table(df) -> str:
    df = df.assign(
        units=df["units"].astype(int).map("{:,}".format),
        order_lines=df["order_lines"].astype(int).map("{:,}".format),
        return_rate=df["return_rate"].map("{:.1%}".format),
    )
    return df.to_html(index=False, border=0, float_format="{:,.2f}".format)


def build_report(db_path: Path, out: Path) -> Path:
    f = an.Filters()
    with duckdb.connect(str(db_path), read_only=True) as con:
        lo, hi = an.bounds(con)
        k = an.kpis(con, f)
        dq = con.execute("select count(*), count(*) filter (where failed_rows = 0) "
                         "from ops.dq_results").fetchone()  # fmt: skip
        products = an.products(con, f, 15)
        parts = [
            _section("Revenue trend", "Net revenue per day in EUR (gross minus refunds, "
                     "all currencies converted at the monthly FX rate).",
                     _fig(charts.revenue_trend(an.daily_revenue(con, f)))),
            _section("Revenue by country", "Net revenue, EUR.",
                     _fig(charts.revenue_by_country(an.revenue_by_country(con, f)))),
            _section("New vs returning customers", "Customers placing at least one order in the month.",
                     _fig(charts.customers_new_vs_returning(an.monthly_customers(con, f)))),
            _section("Cohort retention", "Share of each monthly acquisition cohort that ordered "
                     "again N months after its first order.",
                     _fig(charts.cohort_heatmap(an.cohort_retention(con, f)))),
            _section("RFM customer segments", "Segments from recency and frequency scores "
                     "as of the last order date (monetary is a ranking score only).",
                     _fig(charts.rfm_segments(an.rfm_segments(con, f)))),
            _section("Return rate by category", "Returned order lines as a share of all lines.",
                     _fig(charts.returns_by_category(an.returns_by_category(con, f)))),
            _section("Top products", "Top 15 by net revenue.",
                     _products_table(products)),
        ]  # fmt: skip
    cards = [
        ("Net revenue", f"EUR {k['net_eur']:,.0f}"), ("Orders", f"{k['orders']:,.0f}"),
        ("Avg order value", f"EUR {k['aov_eur']:,.2f}"), ("Customers", f"{k['customers']:,.0f}"),
        ("Return rate", f"{k['return_rate']:.1%}"),
    ]  # fmt: skip
    card_html = "".join(f"<div class='card'><b>{v}</b><span>{html.escape(n)}</span></div>"
                        for n, v in cards)  # fmt: skip
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>E-commerce analytics report</title><style>{CSS}</style>
<script>{get_plotlyjs()}</script></head><body><main>
<h1>E-commerce analytics report</h1>
<p class="sub">Synthetic data, {lo:%d %b %Y} to {hi:%d %b %Y}. Generated by
<code>python -m pipeline report</code>.</p>
<div class="cards">{card_html}</div>
{"".join(parts)}
<footer>Data quality gate: {dq[1]} of {dq[0]} checks passed before transformation.
Source: github.com/Aleksa5000/ecommerce-analytics-pipeline</footer>
</main></body></html>"""
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    return out
